    private void btndaftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndaftarActionPerformed
        String nim = txtnim.getText();
        String nama = txtnama.getText();
        java.text.SimpleDateFormat format =
            new java.text.SimpleDateFormat("yyyy-MM-dd");
        String tanggal = format.format(tanggalLahir.getDate());
        String jenkel = "";
        
        if(rbpria.isSelected()){
            jenkel = "Pria";
        }else if(rbwanita.isSelected()){
            jenkel = "Wanita";
        }
        
        try {
            Connection koneksiDB = koneksi.getkoneksi();

            String sql = "INSERT INTO mahasiswa VALUES (?, ?, ?, ?)";
            PreparedStatement perintah =
                    koneksiDB.prepareStatement(sql);

            perintah.setString(1, nim);
            perintah.setString(2, nama);
            perintah.setString(3, tanggal);
            perintah.setString(4, jenkel);

            perintah.executeUpdate();

            txtarea.setText(
                    "Nim: " + nim
                    + "\nNama: " + nama
                    + "\nTanggal Lahir: " + tanggal
                    + "\nJenis Kelamin: " + jenkel
            );

            JOptionPane.showMessageDialog(this,
                    "Data berhasil disimpan!");

            perintah.close();
            koneksiDB.close();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Gagal menyimpan data: " + e.getMessage());
        }
    }//GEN-LAST:event_btndaftarActionPerformed

    private void btncekActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncekActionPerformed
        String nama = txtnama.getText();
        String jenkel = "";
        int ttl = tanggalLahir.getDate().getYear()+1900;
        int usia = 2026 - ttl;
        
        if(rbpria.isSelected()){
            jenkel = "Pria";
        }else if(rbwanita.isSelected()){
            jenkel = "Wanita";
        }
        
        txtarea.setText(
        "Halo " + nama +
        "\nKamu Adalah " + jenkel +
        "\nBerusia " + usia        
        );
    }//GEN-LAST:event_btncekActionPerformed

