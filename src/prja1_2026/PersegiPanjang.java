        // Procedure untuk menghitung luas
    static int luas(int panjang, int lebar) {
        int hasilLuas = panjang * lebar;
        return hasilLuas;
    }

    // Function untuk menghitung keliling
    static int keliling(int panjang, int lebar) {
        int hasilKeliling = 2 * (panjang + lebar);
        return hasilKeliling;
    }

