    private void btnprosesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnprosesActionPerformed
        try {
            int panjang = Integer.parseInt(txtpanjang.getText());
            int lebar = Integer.parseInt(txtlebar.getText());

            int hasilLuas = luas (panjang, lebar);
            int hasilKeliling = keliling (panjang, lebar);
            // Menampilkan hasil luas dan keliling
            hasil.setText(
                "Luas Persegi Panjang = "+ hasilLuas +
                "\nKeliling Persegi Panjang = " + hasilKeliling
            );

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Masukkan panjang dan lebar dengan angka yang valid!"
            );
        }
    }//GEN-LAST:event_btnprosesActionPerformed

